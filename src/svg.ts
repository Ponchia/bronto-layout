/**
 * Optional DOM/SVG measurement adapter for the framework-neutral host engine.
 * The owning renderer supplies actual elements and stable model identities.
 * This module never queries untrusted selectors, mutates a drawing, or claims
 * to measure rasterized glyph ink or clipped paint.
 */
import type { Rect } from './core.js';
import type { HostGeometryElement, HostGeometrySnapshot } from './host.js';

const SVG_NAMESPACE = 'http://www.w3.org/2000/svg';
const MAX_TARGETS = 256;

type Affine = Pick<DOMMatrixReadOnly, 'a' | 'b' | 'c' | 'd' | 'e' | 'f'>;

export interface SvgHostTarget {
  /** Stable renderer/model element ID; never an autogenerated DOM position. */
  id: string;
  /** Null means an explicitly known target is currently not measurable. */
  element: Element | null;
}

export interface SvgHostCaptureInput {
  root: SVGSVGElement;
  /** All inspected elements, in the same renderer root and model revision. */
  targets: readonly SvgHostTarget[];
  /** Explicit inventory completeness; partial collections must fail closed. */
  inventoryComplete: boolean;
  /** Actual browser viewport in CSS pixels; NOT the SVG viewBox dimensions. */
  viewport: { width: number; height: number; direction?: 'ltr' | 'rtl' };
  /** Optional source revision for subsequent agent/canvas mutation comparisons. */
  revision?: string;
  /**
   * Bounds in SVG root user units. When omitted, root.viewBox.baseVal is used.
   * An unbounded SVG does not acquire invented dimensions.
   */
  rootBounds?: Rect;
}

const finite = (n: number): boolean => typeof n === 'number' && Number.isFinite(n);
const valid = (r: Rect | undefined): r is Rect =>
  Boolean(r && finite(r.x) && finite(r.y) &&
    finite(r.width) && finite(r.height) && r.width > 0 && r.height > 0);
const matrix = (m: Affine | null | undefined): m is Affine =>
  Boolean(m && finite(m.a) && finite(m.b) && finite(m.c) &&
    finite(m.d) && finite(m.e) && finite(m.f));

function corners(box: Rect): Array<{ x: number; y: number }> {
  return [
    { x: box.x, y: box.y },
    { x: box.x + box.width, y: box.y },
    { x: box.x + box.width, y: box.y + box.height },
    { x: box.x, y: box.y + box.height },
  ];
}

function projectToSvg(
  points: readonly { x: number; y: number }[],
  root: Affine,
): Rect | undefined {
  const det = root.a * root.d - root.b * root.c;
  if (!Number.isFinite(det) || Math.abs(det) < 1e-12) return undefined;
  const mapped = points.map((point) => {
    const x = point.x - root.e;
    const y = point.y - root.f;
    return { x: (root.d * x - root.c * y) / det,
      y: (-root.b * x + root.a * y) / det };
  });
  const xs = mapped.map(point => point.x);
  const ys = mapped.map(point => point.y);
  const minX = Math.min(...xs), maxX = Math.max(...xs);
  const minY = Math.min(...ys), maxY = Math.max(...ys);
  const box = { x: minX, y: minY, width: maxX - minX, height: maxY - minY };
  return valid(box) ? box : undefined;
}

function screenCorners(box: Rect, transform: Affine): Array<{ x: number; y: number }> {
  return corners(box).map(point => ({
    x: transform.a * point.x + transform.c * point.y + transform.e,
    y: transform.b * point.x + transform.d * point.y + transform.f,
  }));
}

function insideForeignObject(element: Element, root: SVGSVGElement): boolean {
  let parent: Element | null = element.parentElement as Element | null;
  while (parent && parent !== root) {
    if (parent.namespaceURI === SVG_NAMESPACE && parent.localName.toLowerCase() === 'foreignobject')
      return true;
    parent = parent.parentElement as Element | null;
  }
  return false;
}

const NON_RENDERED_CONTAINERS = new Set([
  'defs', 'clippath', 'mask', 'pattern', 'marker', 'filter', 'symbol',
]);

function underNonRenderedContainer(element: Element, root: SVGSVGElement): boolean {
  let node: Element | null = element;
  while (node && node !== root) {
    if (node.namespaceURI === SVG_NAMESPACE &&
        NON_RENDERED_CONTAINERS.has(node.localName.toLowerCase()))
      return true;
    node = node.parentElement as Element | null;
  }
  return false;
}

function visible(element: Element, root: SVGSVGElement): boolean {
  const view = root.ownerDocument?.defaultView;
  if (!view?.getComputedStyle) return false;
  let node: Element | null = element;
  while (node) {
    let style: CSSStyleDeclaration;
    try { style = view.getComputedStyle(node); } catch { return false; }
    if (style.display === 'none' || style.visibility === 'hidden' ||
        style.visibility === 'collapse' || (style.opacity !== '' && Number(style.opacity) === 0))
      return false;
    if (node === root) return true;
    node = node.parentElement;
  }
  return false;
}

function svgRect(
  root: SVGSVGElement,
  element: Element,
  rootMatrix: Affine,
): Rect | undefined {
  if (!root.contains(element) || element.ownerDocument !== root.ownerDocument ||
      !element.isConnected || !visible(element, root) ||
      underNonRenderedContainer(element, root))
    return undefined;
  try {
    if (element.namespaceURI === SVG_NAMESPACE &&
        typeof (element as SVGGraphicsElement).getBBox === 'function' &&
        typeof (element as SVGGraphicsElement).getScreenCTM === 'function') {
      // SVGGeometryElement.getBBox excludes CSS paint and strokes; CTM maps
      // local geometry into SCREEN, then inverse root CTM returns SVG user units.
      const graphics = element as SVGGraphicsElement;
      const box = graphics.getBBox();
      const transform = graphics.getScreenCTM();
      if (!valid(box) || !matrix(transform)) return undefined;
      return projectToSvg(screenCorners(box, transform), rootMatrix);
    }
    if (element.namespaceURI !== SVG_NAMESPACE &&
        insideForeignObject(element, root) &&
        typeof element.getBoundingClientRect === 'function') {
      // HTML labels inside foreignObject expose CSS border-box bounds, not
      // glyph ink. Inverse root CTM conservatively maps its screen AABB.
      const box = element.getBoundingClientRect();
      if (!valid(box)) return undefined;
      return projectToSvg(corners(box), rootMatrix);
    }
  } catch {
    // Unmounted, unrendered, security-restricted or unsupported SVG geometry
    // is a known unavailable measurement, never a zero-valued or passing box.
  }
  return undefined;
}

/**
 * Capture bounded, renderer-approved target geometry in SVG user units.
 * Call evaluateHostLayout(snapshot, contract) to check reviewed relationships.
 * This does NOT infer intent, query document selectors or verify actual paint.
 */
export function captureSvgHostGeometry(input: SvgHostCaptureInput): HostGeometrySnapshot {
  if (!input || !input.root ||
      input.root.namespaceURI !== SVG_NAMESPACE ||
      input.root.localName.toLowerCase() !== 'svg')
    throw new Error('SVG host capture requires an actual SVG root');
  if (input.inventoryComplete !== true)
    throw new Error('SVG host inventory must be explicitly complete');
  const root = input.root;
  if (!root.isConnected || typeof root.getScreenCTM !== 'function' ||
      typeof root.contains !== 'function')
    throw new Error('SVG root is detached or unmeasurable');
  if (!visible(root, root))
    throw new Error('SVG root is hidden or lacks a measurable document');
  const m = root.getScreenCTM();
  if (!matrix(m) || Math.abs(m.a * m.d - m.b * m.c) < 1e-12)
    throw new Error('SVG root requires an invertible screen CTM');
  const bound = input.rootBounds ?? root.viewBox?.baseVal;
  if (!valid(bound))
    throw new Error('SVG root requires finite, positive viewBox or explicit user bounds');
  const viewport = input.viewport;
  if (!viewport || !Number.isInteger(viewport.width) ||
      viewport.width < 200 || viewport.width > 10000 ||
      !Number.isInteger(viewport.height) || viewport.height <= 0 ||
      (viewport.direction !== undefined && !['ltr', 'rtl'].includes(viewport.direction)))
    throw new Error('SVG host requires an actual CSS-pixel viewport');
  if (!Array.isArray(input.targets) || input.targets.length > MAX_TARGETS)
    throw new Error('SVG host target inventory exceeds bounded collection');
  const identities = new Set<string>();
  const elements: HostGeometryElement[] = [];
  for (const target of input.targets) {
    if (!target || typeof target.id !== 'string' || !target.id.trim() ||
        identities.has(target.id))
      throw new Error('SVG host target IDs must be stable, unique and nonempty');
    identities.add(target.id);
    const rect = target.element ? svgRect(root, target.element, m) : undefined;
    elements.push(rect
      ? { id: target.id, space: 'svg', measurement: 'measured', rect }
      : { id: target.id, space: 'svg', measurement: 'unavailable' });
  }
  return {
    space: 'svg',
    root: { x: bound.x, y: bound.y, width: bound.width, height: bound.height },
    viewport: { ...viewport },
    inventoryComplete: true,
    elements,
    ...(input.revision === undefined ? {} : { revision: input.revision }),
  };
}
